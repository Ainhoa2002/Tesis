"""
SANKEY DIAGRAM VISUALIZER FOR LCA RESULTS
==========================================

This script visualizes Sankey diagrams from the JSON output generated by
result_calculation_explained.py

USAGE:
    1. Run result_calculation_explained.py to generate *_sankey.json files
    2. Run this script to visualize and export interactive HTML diagrams

    python sankey_visualizer.py

DEPENDENCIES:
    - plotly
    - json
    - pathlib
"""

import json
import plotly.graph_objects as go
from pathlib import Path


# ============================================================================
# CONFIGURATION
# ============================================================================

# Directory containing Sankey JSON files
RESULTS_DIR = Path(__file__).parent  # LCI/RESULTS/

# Directory to save HTML visualizations
OUTPUT_DIR = RESULTS_DIR / "sankey_html_exports"

# Color schemes for different visualization modes
COLOR_SCHEMES = {
    1: {  # Flow-based mode
        "nodes": "#3498db",  # Blue
        "edges": "rgba(52, 152, 219, 0.4)"
    },
    2: {  # Impact-based mode
        "nodes": "#e74c3c",  # Red
        "edges": "rgba(231, 76, 60, 0.4)"
    }
}

# Default colors
DEFAULT_NODE_COLOR = "#95a5a6"
DEFAULT_EDGE_COLOR = "rgba(149, 165, 166, 0.4)"


# ============================================================================
# HELPER FUNCTIONS
# ============================================================================

def load_sankey_json(filepath):
    """
    Load Sankey data from JSON file generated by result_calculation_explained.py
    
    Parameters:
        filepath: Path to *_sankey.json file
    
    Returns:
        Dictionary with keys: impact_category, mode, max_nodes, nodes, edges
    """
    with open(filepath, "r", encoding="utf-8") as f:
        return json.load(f)


def create_sankey_figure(sankey_data, title=None):
    """
    Create interactive Plotly Sankey diagram from JSON data.
    
    Parameters:
        sankey_data: Dictionary from load_sankey_json()
        title: Custom title (defaults to impact category name)
    
    Returns:
        plotly.graph_objects.Figure
    
    Example:
        >>> data = load_sankey_json("connector_system_EF_v3.1_sankey.json")
        >>> fig = create_sankey_figure(data)
        >>> fig.show()
    """
    
    # Extract components from sankey_data
    nodes = sankey_data.get("nodes", [])
    edges = sankey_data.get("edges", [])
    mode = sankey_data.get("mode", 1)
    impact_category = sankey_data.get("impact_category", "Unknown")
    
    # Set title
    if not title:
        title = f"{impact_category} (Mode {mode})"
    
    # ========================================================================
    # PREPARE NODE DATA
    # ========================================================================
    
    node_labels = [n["provider"] for n in nodes]
    
    # Color nodes by total_result (magnitude of impact)
    node_values = [n["total_result"] for n in nodes]
    max_value = max(node_values) if node_values else 1
    
    # Normalize values for color intensity (0-1 range)
    normalized_values = [v / max_value for v in node_values]
    
    # Generate colors based on magnitude
    node_colors = []
    for norm_val in normalized_values:
        # Red intensity increases with impact magnitude
        r = int(255 * norm_val)
        g = int(150 * (1 - norm_val))
        b = int(100 * (1 - norm_val))
        node_colors.append(f"rgb({r},{g},{b})")
    
    # ========================================================================
    # PREPARE EDGE DATA
    # ========================================================================
    
    source_nodes = [e["node_index"] for e in edges]
    target_nodes = [e["provider_index"] for e in edges]
    edge_values = [e["upstream_share"] * 100 for e in edges]  # Convert to percentage
    
    # ========================================================================
    # CREATE FIGURE
    # ========================================================================
    
    fig = go.Figure(data=[go.Sankey(
        node=dict(
            pad=15,
            thickness=20,
            line=dict(color="black", width=0.5),
            label=node_labels,
            color=node_colors,
            customdata=[f"Impact: {v:.4f}" for v in node_values],
            hovertemplate='<b>%{label}</b><br>%{customdata}<extra></extra>'
        ),
        link=dict(
            source=source_nodes,
            target=target_nodes,
            value=edge_values,
            color="rgba(200, 200, 200, 0.4)",
            hovertemplate='%{source.label} → %{target.label}<br>Share: %{value:.2f}%<extra></extra>'
        )
    )])
    
    # ========================================================================
    # FORMAT AND STYLE
    # ========================================================================
    
    mode_description = {
        1: "Flow-based (Environmental flows)",
        2: "Impact-based (Impact contributions)"
    }.get(mode, f"Mode {mode}")
    
    fig.update_layout(
        title=dict(
            text=f"<b>{title}</b><br><sub>{mode_description}</sub>",
            x=0.5,
            xanchor="center",
            font=dict(size=16)
        ),
        font=dict(size=12, family="Arial"),
        height=700,
        width=1400,
        plot_bgcolor="white",
        paper_bgcolor="white",
        margin=dict(l=20, r=20, t=100, b=20),
        annotations=[
            dict(
                text=f"<i>Nodes: {len(nodes)} | Edges: {len(edges)}</i>",
                xref="paper", yref="paper",
                x=0.5, y=-0.05,
                showarrow=False,
                font=dict(size=10, color="gray")
            )
        ]
    )
    
    return fig


def visualize_all_sankeyfiles(results_dir=None, output_dir=None):
    """
    Find all Sankey JSON files and create HTML visualizations.
    
    Parameters:
        results_dir: Path to directory containing *_sankey.json files
        output_dir: Path to save HTML files (created if doesn't exist)
    
    Returns:
        List of created HTML file paths
    """
    
    if not results_dir:
        results_dir = RESULTS_DIR
    if not output_dir:
        output_dir = OUTPUT_DIR
    
    results_dir = Path(results_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Find all Sankey JSON files
    sankey_files = list(results_dir.glob("*_sankey.json"))
    
    if not sankey_files:
        print(f"✗ No Sankey files found in {results_dir}")
        return []
    
    print(f"Found {len(sankey_files)} Sankey file(s)")
    print("=" * 70)
    
    created_files = []
    
    for sankey_file in sorted(sankey_files):
        try:
            print(f"\n📊 Processing: {sankey_file.name}")
            
            # Load Sankey data
            sankey_data = load_sankey_json(sankey_file)
            
            # Create figure
            fig = create_sankey_figure(sankey_data)
            
            # Save HTML
            html_filename = sankey_file.stem + "_visualization.html"
            html_path = output_dir / html_filename
            
            fig.write_html(str(html_path))
            created_files.append(html_path)
            
            print(f"   ✓ Created: {html_path.name}")
            print(f"     • Nodes: {len(sankey_data.get('nodes', []))}")
            print(f"     • Edges: {len(sankey_data.get('edges', []))}")
            print(f"     • Mode: {sankey_data.get('mode')} ({'Flow-based' if sankey_data.get('mode') == 1 else 'Impact-based'})")
            
        except Exception as e:
            print(f"   ✗ Error processing {sankey_file.name}: {e}")
    
    print("\n" + "=" * 70)
    print(f"✓ Visualization complete! {len(created_files)} file(s) created in:")
    print(f"  {output_dir}")
    
    return created_files


# ============================================================================
# MAIN EXECUTION
# ============================================================================

if __name__ == "__main__":
    import sys
    
    # Allow custom results directory as command-line argument
    results_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else RESULTS_DIR
    
    # Create all visualizations
    created_files = visualize_all_sankeyfiles(results_dir=results_dir)
    
    if created_files:
        print("\n🎉 Open these HTML files in your browser to view interactive diagrams:")
        for html_file in created_files:
            print(f"   • {html_file}")
