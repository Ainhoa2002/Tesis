"""
SANKEY DIAGRAM VISUALIZER FOR LCA RESULTS
==========================================

This script visualizes Sankey diagrams from the JSON output generated by
result_calculation_explained.py

USAGE:
    1. Run result_calculation_explained.py to generate *_sankey.json files
    2. Run this script to visualize and export interactive HTML diagrams

    python sankey_visualizer.py

DEPENDENCIES:
    - plotly
    - json
    - pathlib
"""

import json
import plotly.graph_objects as go
from pathlib import Path
from collections import defaultdict, deque


# ============================================================================
# CONFIGURATION
# ============================================================================

# Directory containing Sankey JSON files
RESULTS_DIR = Path(__file__).parent / "Deterministic results"
if not RESULTS_DIR.exists():
    RESULTS_DIR = Path(__file__).parent  # LCI/RESULTS/

# Directory to save HTML visualizations
OUTPUT_DIR = RESULTS_DIR / "sankey_html_exports"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# Color schemes for different visualization modes
COLOR_SCHEMES = {
    1: {  # Flow-based mode
        "nodes": "#3498db",  # Blue
        "edges": "rgba(52, 152, 219, 0.4)"
    },
    2: {  # Impact-based mode
        "nodes": "#e74c3c",  # Red
        "edges": "rgba(231, 76, 60, 0.4)"
    }
}

# Default colors
DEFAULT_NODE_COLOR = "#95a5a6"
DEFAULT_EDGE_COLOR = "rgba(149, 165, 166, 0.4)"

# Depth to keep in rendered Sankey (0 = root/product system)
# Use 2 to always show first and second upstream layers.
DISPLAY_MAX_DEPTH = 2

# Node arrangement behavior in Plotly Sankey.
# Use "freeform" so users can drag and reposition nodes in the HTML viewer.
SANKEY_NODE_ARRANGEMENT = "freeform"


# ============================================================================
# HELPER FUNCTIONS
# ============================================================================

def load_sankey_json(filepath):
    """
    Load Sankey data from JSON file generated by result_calculation_explained.py
    
    Parameters:
        filepath: Path to *_sankey.json file
    
    Returns:
        Dictionary with keys: impact_category, mode, max_nodes, nodes, edges
    """
    with open(filepath, "r", encoding="utf-8") as f:
        return json.load(f)


def create_sankey_figure(sankey_data, title=None, max_depth=None):
    """
    Create interactive Plotly Sankey diagram from JSON data.
    
    Parameters:
        sankey_data: Dictionary from load_sankey_json()
        title: Custom title (defaults to impact category name)
        max_depth: Maximum upstream depth to display (defaults to DISPLAY_MAX_DEPTH)
    
    Returns:
        plotly.graph_objects.Figure
    
    Example:
        >>> data = load_sankey_json("connector_system_EF_v3.1_sankey.json")
        >>> fig = create_sankey_figure(data)
        >>> fig.show()
    """
    
    # Use provided max_depth or fall back to configuration
    if max_depth is None:
        max_depth = DISPLAY_MAX_DEPTH
    
    # Extract components from sankey_data
    nodes = sankey_data.get("nodes", [])
    edges = sankey_data.get("edges", [])
    mode = sankey_data.get("mode", 1)
    impact_category = sankey_data.get("impact_category", "Unknown")
    index_to_node = {node["index"]: node for node in nodes}

    # ========================================================================
    # BUILD LAYERED SUBGRAPH (ROOT + LAYER 1 + LAYER 2)
    # ========================================================================
    # Edge direction in data is provider -> receiver.
    # To compute upstream depth from final system(s), we walk reverse edges.
    outgoing = defaultdict(list)
    incoming = defaultdict(list)
    for e in edges:
        src = e["provider_index"]
        tgt = e["node_index"]
        outgoing[src].append(tgt)
        incoming[tgt].append(src)

    # Roots are downstream nodes that do not provide to other nodes.
    candidate_roots = [n["index"] for n in nodes if len(outgoing[n["index"]]) == 0]
    if not candidate_roots and nodes:
        # Fallback: use max total_result node as root.
        root_node = max(nodes, key=lambda n: n.get("total_result", 0))
        candidate_roots = [root_node["index"]]

    depth_map = {}
    queue = deque()
    for root in candidate_roots:
        depth_map[root] = 0
        queue.append(root)

    while queue:
        current = queue.popleft()
        cur_depth = depth_map[current]
        if cur_depth >= max_depth:
            continue
        for upstream in incoming.get(current, []):
            next_depth = cur_depth + 1
            if upstream not in depth_map or next_depth < depth_map[upstream]:
                depth_map[upstream] = next_depth
                queue.append(upstream)

    selected_indices = {idx for idx, depth in depth_map.items() if depth <= max_depth}
    filtered_nodes = [n for n in nodes if n["index"] in selected_indices]
    filtered_edges = [
        e for e in edges
        if e["provider_index"] in selected_indices and e["node_index"] in selected_indices
    ]

    if filtered_nodes and filtered_edges:
        nodes = filtered_nodes
        edges = filtered_edges

    index_to_position = {node["index"]: position for position, node in enumerate(nodes)}
    index_to_node = {node["index"]: node for node in nodes}
    
    # Set title
    if not title:
        title = f"{impact_category} (Mode {mode})"
    
    # ========================================================================
    # PREPARE NODE DATA
    # ========================================================================
    
    node_labels = [n["provider"] for n in nodes]
    
    # Color nodes by total_result (magnitude of impact)
    node_values = [abs(float(n.get("total_result", 0) or 0.0)) for n in nodes]
    max_value = max(node_values) if node_values else 1
    
    # Normalize values for color intensity (0-1 range)
    normalized_values = [v / max_value for v in node_values]
    
    # Generate colors based on magnitude
    node_colors = []
    for norm_val in normalized_values:
        # Red intensity increases with impact magnitude
        r = int(255 * norm_val)
        g = int(150 * (1 - norm_val))
        b = int(100 * (1 - norm_val))
        node_colors.append(f"rgb({r},{g},{b})")
    
    # ========================================================================
    # PREPARE EDGE DATA
    # ========================================================================
    
    edge_records = []
    for e in edges:
        src_idx = e.get("provider_index")
        tgt_idx = e.get("node_index")
        if src_idx not in index_to_position or tgt_idx not in index_to_position:
            continue

        target_node = index_to_node.get(tgt_idx)
        source_node = index_to_node.get(src_idx)
        if target_node is None:
            continue

        share = float(e.get("upstream_share", 0.0) or 0.0)
        target_total = float(target_node.get("total_result", 0.0) or 0.0)
        source_total = float(source_node.get("total_result", 0.0) or 0.0) if source_node else 0.0

        # Primary rule: scale links from the provider contribution, so first-layer
        # modules are not forced to equal size when upstream_share is 1.0 for all.
        # Fallback: if provider total is unavailable, use receiving-node based value.
        contribution_base = source_total
        if abs(contribution_base) < 1e-20 and abs(target_total) >= 1e-20:
            contribution_base = target_total

        signed_contribution = share * contribution_base
        magnitude = abs(signed_contribution)
        if magnitude <= 0.0:
            continue

        edge_records.append(
            {
                "source": index_to_position[src_idx],
                "target": index_to_position[tgt_idx],
                "value": magnitude,
                "share": share,
                "signed": signed_contribution,
            }
        )

    source_nodes = [item["source"] for item in edge_records]
    target_nodes = [item["target"] for item in edge_records]
    edge_values = [item["value"] for item in edge_records]
    edge_hover_data = [
        f"Share: {item['share']:.2%}<br>Signed contribution: {item['signed']:.6g}"
        for item in edge_records
    ]
    
    # ========================================================================
    # CREATE FIGURE
    # ========================================================================
    
    # Explicit node positioning by depth to keep each layer clearly separated.
    by_depth = defaultdict(list)
    for n in nodes:
        d = depth_map.get(n["index"], max_depth)
        by_depth[d].append(n["index"])

    max_depth_in_graph = max(by_depth.keys()) if by_depth else max_depth
    depth_den = max(max_depth_in_graph, 1)

    node_x = [0.5] * len(nodes)
    node_y = [0.5] * len(nodes)
    for d, idxs in by_depth.items():
        idxs_sorted = sorted(idxs, key=lambda i: index_to_node[i].get("total_result", 0), reverse=True)
        for k, idx in enumerate(idxs_sorted):
            pos = index_to_position[idx]
            node_x[pos] = 1.0 - (d / depth_den)
            node_y[pos] = (k + 1) / (len(idxs_sorted) + 1)

    fig = go.Figure(data=[go.Sankey(
        arrangement=SANKEY_NODE_ARRANGEMENT,
        node=dict(
            pad=15,
            thickness=20,
            line=dict(color="black", width=0.5),
            label=node_labels,
            color=node_colors,
            x=node_x,
            y=node_y,
            customdata=[f"Impact magnitude: {v:.6g}" for v in node_values],
            hovertemplate='<b>%{label}</b><br>%{customdata}<extra></extra>'
        ),
        link=dict(
            source=source_nodes,
            target=target_nodes,
            value=edge_values,
            color="rgba(200, 200, 200, 0.4)",
            customdata=edge_hover_data,
            hovertemplate='%{source.label} → %{target.label}<br>%{customdata}<br>Width contribution magnitude: %{value:.6g}<extra></extra>'
        )
    )])
    
    # ========================================================================
    # FORMAT AND STYLE
    # ========================================================================
    
    mode_description = {
        1: "Flow-based (Environmental flows)",
        2: "Impact-based (Impact contributions)"
    }.get(mode, f"Mode {mode}")
    
    fig.update_layout(
        title=dict(
            text=f"<b>{title}</b><br><sub>{mode_description}</sub>",
            x=0.5,
            xanchor="center",
            font=dict(size=16)
        ),
        font=dict(size=12, family="Arial"),
        height=700,
        width=1400,
        plot_bgcolor="white",
        paper_bgcolor="white",
        margin=dict(l=20, r=20, t=100, b=20),
        annotations=[
            dict(
                text=f"<i>Nodes: {len(nodes)} | Edges: {len(edges)}</i>",
                xref="paper", yref="paper",
                x=0.5, y=-0.05,
                showarrow=False,
                font=dict(size=10, color="gray")
            )
        ]
    )
    
    return fig


def visualize_all_sankeyfiles(results_dir=None, output_dir=None):
    """
    Find all Sankey JSON files and create HTML visualizations.
    
    Parameters:
        results_dir: Path to directory containing *_sankey.json files
        output_dir: Path to save HTML files (created if doesn't exist)
    
    Returns:
        List of created HTML file paths
    """
    
    if not results_dir:
        results_dir = RESULTS_DIR
    if not output_dir:
        output_dir = OUTPUT_DIR
    
    results_dir = Path(results_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Find all Sankey JSON files
    sankey_files = list(results_dir.glob("*_sankey.json"))
    
    if not sankey_files:
        print(f"✗ No Sankey files found in {results_dir}")
        return []
    
    print(f"Found {len(sankey_files)} Sankey file(s)")
    print("=" * 70)
    
    created_files = []
    
    for sankey_file in sorted(sankey_files):
        try:
            print(f"\n📊 Processing: {sankey_file.name}")
            
            # Load Sankey data
            sankey_data = load_sankey_json(sankey_file)
            
            # Create figure
            fig = create_sankey_figure(sankey_data)
            
            # Save HTML
            html_filename = sankey_file.stem + "_visualization.html"
            html_path = output_dir / html_filename
            
            fig.write_html(str(html_path))
            created_files.append(html_path)
            
            print(f"   ✓ Created: {html_path.name}")
            print(f"     • Nodes: {len(sankey_data.get('nodes', []))}")
            print(f"     • Edges: {len(sankey_data.get('edges', []))}")
            print(f"     • Mode: {sankey_data.get('mode')} ({'Flow-based' if sankey_data.get('mode') == 1 else 'Impact-based'})")
            
        except Exception as e:
            print(f"   ✗ Error processing {sankey_file.name}: {e}")
    
    print("\n" + "=" * 70)
    print(f"✓ Visualization complete! {len(created_files)} file(s) created in:")
    print(f"  {output_dir}")
    
    return created_files


# ============================================================================
# MAIN EXECUTION
# ============================================================================

if __name__ == "__main__":
    import sys
    
    # Allow custom results directory as command-line argument
    results_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else RESULTS_DIR
    
    # Create all visualizations
    created_files = visualize_all_sankeyfiles(results_dir=results_dir)
    
    if created_files:
        print("\n🎉 Open these HTML files in your browser to view interactive diagrams:")
        for html_file in created_files:
            print(f"   • {html_file}")
